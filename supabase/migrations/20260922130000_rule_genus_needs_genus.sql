-- Плашка правила утверждает, что род слова предсказуем. У слова без рода
-- предсказывать нечего: у имён собственных и у слов только во
-- множественном числе рода нет вовсе, и правило там означало бы, что
-- тренажёр спрашивает несуществующий артикль.
--
-- Ограничение закрывает это на уровне схемы, а не на уровне внимательности
-- того, кто заливает словарь.

alter table public.words
  add constraint words_rule_genus_needs_genus
  check (rule_genus is null or genus is not null);
