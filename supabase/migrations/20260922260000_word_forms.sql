-- Формы слова, которым нет отдельного поля.
--
-- Частотный список даёт «jeder, jede, jedes», «andere (r, s)»,
-- «vorne, vorn» — это одно слово, а не три, поэтому карточка одна.
-- Но показать формы негде: Singular/Plural есть у существительного,
-- пять лиц у глагола, а у определителя и наречия нет ничего, и формы
-- просто пропадали. Слово в заголовке стояло одно, остальные терялись.
--
-- Поле общее, а не «формы по родам»: у vorne/vorn это варианты
-- написания, а не роды, и называть их родами значило бы соврать.
-- Подпись на карточке — «Formen», как и прочие немецкие подписи форм.

alter table public.words
  add column forms text[] not null default '{}';

comment on column public.words.forms is
  'Формы слова, которым нет своего поля: роды определителя, варианты написания. Показываются одной строкой «Formen».';
