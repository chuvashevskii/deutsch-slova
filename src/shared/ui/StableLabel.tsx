/**
 * Подпись кнопки-переключателя, не меняющая ширину.
 *
 * У такой кнопки текст меняется на заметно более длинный — «Знаю» →
 * «Вернуть в колоду», четыре знака против шестнадцати. Кнопка от этого
 * росла вчетверо, ряд с `flex-wrap` пересобирался, и соседняя кнопка
 * перескакивала на другую строку — прямо под пальцем, который ещё
 * не оторвался от экрана.
 *
 * Обе подписи лежат в одной ячейке грида, одна над другой. Ячейка берёт
 * ширину по длинной из них, и переключение больше ничего не двигает —
 * ни вперёд, ни назад.
 *
 * Скрытая подпись стоит именно `invisible`, а не `hidden`: место она
 * занимать обязана, ради того и существует. От чтения с экрана она
 * убрана — иначе кнопка «Знаю» читалась бы как «Знаю Вернуть в колоду».
 */
export const StableLabel = ({ shown, other }: { shown: string; other: string }) => (
  <span className="grid justify-items-center">
    <span className="col-start-1 row-start-1">{shown}</span>
    <span className="invisible col-start-1 row-start-1" aria-hidden>
      {other}
    </span>
  </span>
);
