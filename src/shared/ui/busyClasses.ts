/**
 * Классы кнопки, у которой идёт запрос.
 *
 * Гашение до 40% оставлено настоящему запрету — «это сейчас нельзя».
 * Запрос это не запрет, а ожидание: кнопка остаётся в своём цвете,
 * иначе тёмная кнопка со светлой крутилкой превращается в серое пятно.
 * Нажать её всё равно нельзя, и курсор об этом говорит.
 */
export const busyClasses = (busy: boolean) => (busy ? 'cursor-wait' : 'disabled:opacity-40');
