/**
 * Родовые окончания определителя.
 *
 * `jeder`, `kein`, `welcher` и прочие меняются по роду существительного,
 * и на карточке это ничем не видно: заголовок стоит один, мужского рода,
 * а в примерах случайно оказывается та же форма. Человек не узнаёт,
 * что слово вообще склоняется.
 *
 * Формами решено не показывать: тогда пришлось бы объяснять, почему
 * у `groß` нет `großer / große / großes`, — это был бы третий формат
 * карточки ради семи слов. Показывается только **окончание**:
 * напоминание о правиле, а не набор форм для заучивания.
 *
 * Образцов два, и путать их нельзя.
 *
 * **der-слова** берут окончание во всех трёх родах: `jeder Mann`,
 * `jede Frau`, `jedes Kind`.
 *
 * **ein-слова** в мужском и среднем роде окончания не имеют вовсе:
 * `kein Mann`, `keine Frau`, `kein Kind`. Написать им `-er` значило бы
 * научить неправильному.
 */
export interface DeterminerForms {
  /** Основа без окончания. Пусто, когда окончаниями слово не описывается. */
  stem: string;
  /** Мужской, женский, средний — в том же порядке, что цвета рода на карточке. */
  endings: [string, string, string];
  /** Формы целиком — для слова, у которого меняется не хвост. */
  forms: [string, string, string];
}

/**
 * Основа задана явно, а не вычислена общим началом форм.
 *
 * Вычисление казалось очевидным и дало неверное: у `jeder / jede / jedes`
 * самое длинное общее начало — `jede`, и женское окончание `-e` в него
 * попадает целиком. Карточка показывала «jede «r» · «—» · «s»», то есть
 * утверждала, что в женском роде окончания нет. Морфологическую основу
 * из трёх строк не вывести, а слов всего семь — они перечислены и каждое
 * проверено глазами.
 *
 * Правило «местоимение → склоняется» тоже неверно: `man`, `nichts`,
 * `wer` не меняются вовсе, и списка это не касается.
 */
const PATTERNS: Record<string, DeterminerForms> = {
  jeder: {
    stem: 'jed',
    endings: ['-er', '-e', '-es'],
    forms: ['jeder', 'jede', 'jedes'],
  },
  mancher: {
    stem: 'manch',
    endings: ['-er', '-e', '-es'],
    forms: ['mancher', 'manche', 'manches'],
  },
  solcher: {
    stem: 'solch',
    endings: ['-er', '-e', '-es'],
    forms: ['solcher', 'solche', 'solches'],
  },
  welcher: {
    stem: 'welch',
    endings: ['-er', '-e', '-es'],
    forms: ['welcher', 'welche', 'welches'],
  },
  // INFO: ein-слова. Прочерк — это «окончания нет», и он написан знаком,
  // а не оставлен пустым местом: пустота читалась бы как «забыли
  // заполнить», а здесь пусто по правилу.
  kein: {
    stem: 'kein',
    endings: ['—', '-e', '—'],
    forms: ['kein', 'keine', 'kein'],
  },
  irgendein: {
    stem: 'irgendein',
    endings: ['—', '-e', '—'],
    forms: ['irgendein', 'irgendeine', 'irgendein'],
  },
  // INFO: здесь меняется не хвост, а артикль внутри слова. Назвать
  // «-erselbe» окончанием значило бы соврать, поэтому основы нет
  // и показываются формы целиком.
  derselbe: {
    stem: '',
    endings: ['', '', ''],
    forms: ['derselbe', 'dieselbe', 'dasselbe'],
  },
};

/** Окончания определителя или `null`, если слово по роду не меняется. */
export const determinerForms = (head: string): DeterminerForms | null =>
  PATTERNS[head.toLowerCase()] ?? null;
