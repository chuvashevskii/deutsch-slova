-- Карточка никогда не выходила из стадии заучивания: «Хорошо» возвращало
-- слово через десять минут и на шестой раз, и на шестидесятый.
--
-- Планировщик FSRS держит номер шага заучивания в поле learning_steps.
-- В таблице такой колонки не было, а при чтении из базы поле жёстко
-- подставлялось нулём — то есть каждый ответ возвращал карточку на нулевой
-- шаг. Следствием этого scheduled_days оставался нулём, и статусы «учу»
-- и «знаю» не наступали никогда: весь прогресс стоял на месте.

alter table public.cards
  add column learning_steps integer not null default 0;

comment on column public.cards.learning_steps is
  'Номер шага заучивания в FSRS. Без него карточка не выпускается из стадии заучивания.';
