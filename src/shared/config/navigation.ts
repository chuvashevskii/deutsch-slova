/**
 * Разделы приложения — один список на боковую навигацию, нижнюю панель
 * и страницу «Ещё». Раньше он был записан дважды, и добавить раздел
 * значило не забыть про второе место.
 *
 * Деление на ежедневное и редкое придумано не ради красоты: внизу
 * телефона помещается четыре вкладки, а разделов шесть. «Учить»,
 * «Слова» и «Статистика» должны оставаться в одно касание, остальное
 * уходит под «Ещё». На широком экране второго этажа не нужно —
 * в колонке слева хватает места на всё сразу.
 */
export interface NavSection {
  to: string;
  label: string;
  icon: string;
  /** Совпадение только по точному пути: иначе «/» подсвечен везде. */
  end?: boolean;
  /** Подпись на странице «Ещё»: в узкой колонке для неё места нет. */
  hint?: string;
}

