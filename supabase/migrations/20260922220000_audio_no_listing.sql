-- Политика на storage.objects давала всем вошедшим право SELECT по строкам
-- бакета, а это не «читать файлы», а «получить список файлов целиком».
--
-- Публичному бакету она не нужна вовсе: содержимое отдаётся по прямой
-- ссылке /storage/v1/object/public/…, минуя политики. То есть политика
-- ничего не открывала для приложения и при этом позволяла перечислить
-- всё хранилище постороннему.
--
-- Скрипт заливки список читает служебным ключом, а он политики обходит,
-- так что заливка от снятия не страдает.

drop policy if exists "Озвучка читается всеми" on storage.objects;
